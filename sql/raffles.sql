-- Histórico de sorteios mensais (out/2026) — A APLICAR pelo dono no SQL Editor do Supabase.
-- Aditivo e idempotente: só cria a tabela se não existir. Não mexe em nenhuma outra tabela.
-- O admin (aba Sorteio) lê e grava pela Edge Function admin-db (service role, com senha).
-- Guarda só nome, código do pedido e cidade dos ganhadores — NUNCA CPF, telefone ou e-mail.

create table if not exists public.raffles (
  -- id definido pelo site (Date.now() do sorteio); permite importar o histórico antigo sem duplicar
  id            bigint generated by default as identity primary key,
  mes           text        not null check (mes ~ '^\d{4}-(0[1-9]|1[0-2])$'), -- mês de referência 'YYYY-MM'
  sorteado_em   timestamptz not null default now(),                           -- data/hora do sorteio
  participantes integer     not null default 0,                               -- nº de participantes elegíveis
  excluidos     integer     not null default 0,                               -- quantos foram excluídos à mão
  qtd_ganhadores integer    not null default 0,                               -- quantidade de ganhadores
  ganhadores    jsonb       not null default '[]'::jsonb,                     -- [{name, code, city}]
  created_at    timestamptz not null default now()
);

create index if not exists raffles_mes_idx on public.raffles (mes);

-- RLS ligado e NENHUMA política: visitante (anon/authenticated) não lê nem grava.
-- Só a service role (admin-db) acessa, igual a orders/expenses (ver sql/rls_protect_data.sql).
alter table public.raffles enable row level security;
do $$
declare r record;
begin
  for r in select policyname from pg_policies where schemaname = 'public' and tablename = 'raffles' loop
    execute format('drop policy %I on public.raffles', r.policyname);
  end loop;
end $$;

-- Conferência: deve devolver 1 linha com rls = true e politicas = 0
select c.relname as tabela, c.relrowsecurity as rls,
       (select count(*) from pg_policies p where p.schemaname = 'public' and p.tablename = c.relname) as politicas
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname = 'raffles';
