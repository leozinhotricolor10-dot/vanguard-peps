-- Participantes manuais do sorteio mensal (clientes que compraram fora do site) — A APLICAR pelo dono no SQL Editor do Supabase.
-- Aditivo e idempotente: só cria a tabela se não existir. Não mexe em nenhuma outra tabela.
-- O admin (aba Sorteio) lê e grava pela Edge Function admin-db (service role, com senha); a admin-db precisa ser publicada com `raffle_extras` em TABLES.
-- Guarda nome, observação e telefone (opcional, só para o botão de WhatsApp do admin). O telefone NUNCA vai para o histórico `raffles`.

create table if not exists public.raffle_extras (
  id         bigint generated by default as identity primary key,
  mes        text        not null check (mes ~ '^\d{4}-(0[1-9]|1[0-2])$'), -- mês do sorteio 'YYYY-MM'
  nome       text        not null,                                           -- nome já limpo (sem emoji/numeração)
  obs        text,                                                          -- observação (ex.: texto original colado)
  telefone   text,                                                          -- opcional; usado só no botão de WhatsApp
  created_at timestamptz not null default now()
);

create index if not exists raffle_extras_mes_idx on public.raffle_extras (mes);

-- RLS ligado e NENHUMA política: visitante (anon/authenticated) não lê nem grava.
-- Só a service role (admin-db) acessa, igual a orders/expenses/raffles (ver sql/rls_protect_data.sql).
alter table public.raffle_extras enable row level security;
do $$
declare r record;
begin
  for r in select policyname from pg_policies where schemaname = 'public' and tablename = 'raffle_extras' loop
    execute format('drop policy %I on public.raffle_extras', r.policyname);
  end loop;
end $$;

-- Conferência: deve devolver 1 linha com rls = true e politicas = 0
select c.relname as tabela, c.relrowsecurity as rls,
       (select count(*) from pg_policies p where p.schemaname = 'public' and p.tablename = c.relname) as politicas
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relname = 'raffle_extras';
